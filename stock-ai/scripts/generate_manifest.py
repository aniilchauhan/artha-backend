"""
Generates artifact_manifest.json cataloging all existing models, calibrations,
and outputs with their cryptographic hashes, sizes, timestamps, and provenance.
"""

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
MODELS_DIR = BASE_DIR / "models"
OUTPUTS_DIR = BASE_DIR / "outputs"


def get_hash(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()[:16]


def generate_manifest():
    manifest = {
        "manifest_version": "2.0-candidate",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "provenance_standard": "ISO-8601-UTC",
        "specification_reference": "docs/TARGET_SPECIFICATION.md",
        "target_version": "2.0-executable",
        "preprocessing_version": "2.0-temporal-isolated",
        "reproduction_command": "python stock-ai/src/train.py --universe all --clean --calibrated",
        "split_dates": {
            "train": "2020-09-01 -> 2023-12-31",
            "tuning": "2024-01-01 -> 2024-12-31",
            "calibration": "2025-01-01 -> 2025-06-30",
            "untouched_test": "2025-07-01 -> 2026-12-31",
        },
        "limitations": [
            "No synthetic sentiment or institutional-flow features permitted in candidate promotion.",
            "Probability calibration performed on isolated calibration window disjoint from tuning.",
            "Untouched holdout reserved exclusively for virgin prospective evaluation.",
            "Daily bars evaluate executable entry (Next Open) with conservative stop-first resolution.",
        ],
        "artifacts": [],
    }

    directories = [
        (MODELS_DIR, "model_artifact"),
        (OUTPUTS_DIR, "output_artifact"),
    ]

    for d, cat in directories:
        for p in sorted(d.rglob("*")):
            if (
                p.is_file()
                and not p.name.endswith(".pyc")
                and "__pycache__" not in str(p)
                and "artifact_manifest.json" not in p.name
            ):
                rel = str(p.relative_to(BASE_DIR)).replace("\\", "/")
                stat = p.stat()
                size = stat.st_size
                mtime = datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat()

                # Provenance classification
                target_def = "Next Day High >= Today Close * (1 + 0.02)"
                verified = False
                training_period = "2020-09-01 -> 2024-06-30"
                evaluation_period = "2025-07-01 -> 2026-09-04"

                if "imputation_values.json" in p.name:
                    verified = True
                    notes = (
                        "Verified: Fitted exclusively on training fold (2020-11 to 2024-06) "
                        "under temporal isolation."
                    )
                elif "lightgbm_stock_model.pkl" in p.name:
                    notes = (
                        "Unverified: Legacy base ensemble weights. Target: close-to-high +2%. "
                        "Flagged as REQUIRES_REGENERATION under executable target."
                    )
                elif "lightgbm_calibrated.pkl" in p.name:
                    notes = (
                        "Unverified: Legacy isotonic calibration fitted on legacy validation fold."
                    )
                elif "latest_predictions" in p.name:
                    notes = (
                        "Bundled snapshot: Predictions generated by legacy model for 2026-09-07. "
                        "Used as reference research snapshot, not live executable signal."
                    )
                elif "paper_trading" in p.name:
                    notes = (
                        "Demonstration sandbox traces for paper broker simulation."
                    )
                elif "evaluation_report.json" in p.name:
                    notes = (
                        "Legacy evaluation metrics: 66.5% ROC-AUC on close-to-high event. "
                        "Does not reflect executable trade outcomes."
                    )
                else:
                    notes = "Supporting model/output artifact."

                manifest["artifacts"].append(
                    {
                        "path": rel,
                        "category": cat,
                        "size_bytes": size,
                        "sha256_prefix": get_hash(p),
                        "last_modified": mtime,
                        "target_definition": target_def,
                        "training_period": training_period,
                        "evaluation_period": evaluation_period,
                        "verified_reproducibility": verified,
                        "notes": notes,
                    }
                )

    out_path = OUTPUTS_DIR / "artifact_manifest.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print(f"Generated manifest with {len(manifest['artifacts'])} artifacts at {out_path}")


if __name__ == "__main__":
    generate_manifest()
