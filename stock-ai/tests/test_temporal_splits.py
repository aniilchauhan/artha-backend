"""
Test suite for Four-Period Chronological Partitioning (M5-05) and Strict Temporal Isolation.
Verifies:
1. Configuration declares 4 non-overlapping temporal windows (Train, Tuning, Calibration, Untouched Test).
2. Partitions generated by get_four_period_splits() are strictly disjoint.
3. Boundary leaks across consecutive partitions are trimmed.
4. Imputation parameters are computed exclusively from the training partition.
5. Synthetic feature flags strictly reject synthetic features when clean mode is active.
"""

import sys
import unittest
from pathlib import Path
import numpy as np
import pandas as pd

# Add stock-ai to path
STOCK_AI_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(STOCK_AI_DIR))

import config
from src import dataset, features


class TestFourPeriodSplits(unittest.TestCase):

    def test_config_splits_are_chronologically_ordered_and_disjoint(self):
        """Verify configuration date boundaries form strict monotonically increasing windows."""
        train_start = pd.to_datetime(config.TRAIN_START)
        train_end = pd.to_datetime(config.TRAIN_END)
        tuning_start = pd.to_datetime(config.TUNING_START)
        tuning_end = pd.to_datetime(config.TUNING_END)
        cal_start = pd.to_datetime(config.CALIBRATION_START)
        cal_end = pd.to_datetime(config.CALIBRATION_END)
        test_start = pd.to_datetime(config.UNTOUCHED_TEST_START)
        test_end = pd.to_datetime(config.UNTOUCHED_TEST_END)

        self.assertLessEqual(train_start, train_end, "Train start must be before or equal to train end")
        self.assertLess(train_end, tuning_start, "Train end must precede tuning start (no temporal overlap)")
        self.assertLessEqual(tuning_start, tuning_end, "Tuning start must be before or equal to tuning end")
        self.assertLess(tuning_end, cal_start, "Tuning end must precede calibration start (no overlap)")
        self.assertLessEqual(cal_start, cal_end, "Calibration start must be before or equal to calibration end")
        self.assertLess(cal_end, test_start, "Calibration end must precede untouched test start (no overlap)")
        self.assertLessEqual(test_start, test_end, "Untouched test start must be before or equal to test end")

    def test_get_four_period_splits_disjointness_and_buffering(self):
        """Verify get_four_period_splits produces disjoint subsets with trimmed boundaries."""
        # Generate synthetic daily data spanning all 4 periods
        dates = pd.date_range("2020-09-01", "2026-12-31", freq="B")
        np.random.seed(42)
        n = len(dates)
        synthetic_df = pd.DataFrame({
            "Date": dates,
            "ticker": "TEST.NS",
            "feature_alpha": np.random.randn(n),
            "feature_beta": np.random.randn(n),
            "target": np.random.choice([0.0, 1.0], size=n),
        })
        # Add some NaNs in feature_alpha to test imputation isolation
        synthetic_df.loc[10:15, "feature_alpha"] = np.nan

        train_df, tuning_df, cal_df, test_df = dataset.get_four_period_splits(
            df=synthetic_df,
            drop_unlabeled=True,
            apply_train_imputation=True,
            drop_boundary_leaks=True,
        )

        self.assertFalse(train_df.empty, "Train partition must not be empty")
        self.assertFalse(tuning_df.empty, "Tuning partition must not be empty")
        self.assertFalse(cal_df.empty, "Calibration partition must not be empty")
        self.assertFalse(test_df.empty, "Untouched test partition must not be empty")

        # Check disjointness
        self.assertLess(train_df["Date"].max(), tuning_df["Date"].min(), "Train must strictly precede Tuning")
        self.assertLess(tuning_df["Date"].max(), cal_df["Date"].min(), "Tuning must strictly precede Calibration")
        self.assertLess(cal_df["Date"].max(), test_df["Date"].min(), "Calibration must strictly precede Untouched Test")

        # Check total rows <= original rows (boundary rows dropped)
        combined_count = len(train_df) + len(tuning_df) + len(cal_df) + len(test_df)
        self.assertLessEqual(combined_count, len(synthetic_df))

    def test_training_imputation_isolation_across_four_splits(self):
        """Verify median imputation values are calculated strictly on the training partition."""
        train_dates = pd.date_range("2020-09-01", "2023-12-31", freq="W")
        tuning_dates = pd.date_range("2024-01-01", "2024-12-31", freq="W")
        cal_dates = pd.date_range("2025-01-01", "2025-06-30", freq="W")
        test_dates = pd.date_range("2025-07-01", "2026-12-31", freq="W")

        all_dates = list(train_dates) + list(tuning_dates) + list(cal_dates) + list(test_dates)
        df = pd.DataFrame({
            "Date": all_dates,
            "ticker": "TEST.NS",
            "target": 1.0,
            "metric_1": [10.0] * len(all_dates),
        })

        # Set specific train values: median should be 5.0
        train_indices = df[df["Date"] <= "2023-12-31"].index
        df.loc[train_indices, "metric_1"] = 5.0

        # Inject NaNs across test and tuning
        test_indices = df[df["Date"] >= "2025-07-01"].index
        df.loc[test_indices[:5], "metric_1"] = np.nan

        train_df, tuning_df, cal_df, test_df = dataset.get_four_period_splits(
            df=df,
            apply_train_imputation=True,
            drop_boundary_leaks=False,
        )

        # The imputed test values must equal the TRAIN median (5.0), not anything else
        for idx in range(5):
            self.assertEqual(
                test_df.iloc[idx]["metric_1"],
                5.0,
                "Test partition missing values must be imputed with train median (5.0)"
            )


if __name__ == "__main__":
    unittest.main()
